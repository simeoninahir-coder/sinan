-- =====================================================================
-- SINAN ERP · 16 - FECHAS IMPORTANTES (arriba del calendario de contenido)
-- Las fechas que se agregan a mano. Eventos y fiestas se calculan solos.
-- No borra datos. Se puede volver a correr.
-- =====================================================================
create table if not exists fechas_importantes (
  id      bigint generated by default as identity primary key,
  fecha   date not null,
  nombre  text not null,
  creado  timestamptz not null default now()
);
alter table fechas_importantes enable row level security;
drop policy if exists "solo usuarios logueados" on fechas_importantes;
create policy "solo usuarios logueados" on fechas_importantes for all to authenticated using (true) with check (true);
revoke all on fechas_importantes from anon;
grant select, insert, update, delete on fechas_importantes to authenticated;
grant usage, select on all sequences in schema public to authenticated;
revoke usage, select on all sequences in schema public from anon;
